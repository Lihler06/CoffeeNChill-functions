using System.Net;
using System.Text.Json;
using Azure;
using Azure.Storage.Queues;
using CoffeeNChill.Functions.Models;
using Microsoft.Azure.Functions.Worker;
using Microsoft.Azure.Functions.Worker.Http;
using Microsoft.Extensions.Logging;

namespace CoffeeNChill.Functions.Functions
{
    public class OrderFunctions
    {
        private readonly QueueClient _queueClient;
        private readonly ILogger<OrderFunctions> _logger;
        private static readonly JsonSerializerOptions ReadOptions = new(JsonSerializerDefaults.Web);

        public OrderFunctions(QueueClient queueClient, ILogger<OrderFunctions> logger)
        {
            _queueClient = queueClient;
            _logger = logger;
        }

        // POST /api/orders/queue -> validate the order and push it onto order-processing-queue

        [Function("PlaceOrder")]
        public async Task<HttpResponseData> PlaceOrder(
        [HttpTrigger(AuthorizationLevel.Anonymous, "post", Route = "orders/queue")] HttpRequestData req)
        {
            _logger.LogInformation("Placing a new order on the queue.");

            OrderRequestDto? dto;
            try
            {
                var body = await req.ReadAsStringAsync();
                if (string.IsNullOrWhiteSpace(body))
                    return await Error(req, HttpStatusCode.BadRequest, "Request body cannot be empty.");
                dto = JsonSerializer.Deserialize<OrderRequestDto>(body, ReadOptions);
            }
            catch (JsonException)
            {
                return await Error(req, HttpStatusCode.BadRequest, "Malformed JSON in request body.");
            }

            if (dto is null)
                return await Error(req, HttpStatusCode.BadRequest, "Request body could not be parsed.");

            var validationError = ValidateOrder(dto);
            if (validationError is not null)
                return await Error(req, HttpStatusCode.BadRequest, validationError);

            // The timestamp is generated by the server here.
            var order = new Order
            {
                OrderId = dto.OrderId!.Trim(),
                CustomerName = dto.CustomerName!.Trim(),
                SelectedItemSKUs = dto.SelectedItemSKUs!.Select(s => s.Trim()).ToList(),
                TotalPrice = dto.TotalPrice!.Value,
                OrderTimestamp = DateTime.UtcNow
            };

            try
            {
                var message = JsonSerializer.Serialize(order);
                await _queueClient.CreateIfNotExistsAsync();
                await _queueClient.SendMessageAsync(message);
                _logger.LogInformation("Order {OrderId} placed on order-processing-queue.", order.OrderId);
            }
            catch (RequestFailedException ex)
            {
                _logger.LogError(ex, "Queue Storage error while placing order {OrderId}.", order.OrderId);
                return await Error(req, HttpStatusCode.ServiceUnavailable,
                "The order queue is currently unavailable. Please try again shortly.");
            }

            var response = req.CreateResponse(HttpStatusCode.Accepted);
            await response.WriteAsJsonAsync(new
            {
                message = "Order accepted and queued for processing.",
                orderId = order.OrderId,
                orderTimestamp = order.OrderTimestamp,
                status = "Queued"
            });
            return response;
        }

        

        private static string? ValidateOrder(OrderRequestDto dto)
        {
            if (string.IsNullOrWhiteSpace(dto.OrderId)) return "OrderId is required.";
            if (string.IsNullOrWhiteSpace(dto.CustomerName)) return "CustomerName is required.";
            if (dto.SelectedItemSKUs is null || dto.SelectedItemSKUs.Count == 0)
                return "SelectedItemSKUs must contain at least one SKU.";
            if (dto.SelectedItemSKUs.Any(string.IsNullOrWhiteSpace))
                return "SelectedItemSKUs cannot contain empty values.";
            if (dto.TotalPrice is null) return "TotalPrice is required.";
            if (dto.TotalPrice <= 0) return "TotalPrice must be greater than zero.";
            return null;
        }

        private static async Task<HttpResponseData> Error(HttpRequestData req, HttpStatusCode statusCode, string message)
        {
            var response = req.CreateResponse(statusCode);
            await response.WriteAsJsonAsync(new { error = message });
            return response;
        }
    }
}